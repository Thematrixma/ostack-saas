/* =========================================================
   رسم Radar Chart بسيط بصيغة SVG لنتيجة DISC
   ========================================================= */
function renderRadarChart(containerId, percentages) {
  const el = document.getElementById(containerId);
  if (!el) return;

  const center = 100;
  const maxR = 78;
  const axes = ["D", "I", "S", "C"];
  const angleStep = (Math.PI * 2) / axes.length;

  function pointFor(index, value) {
    const angle = -Math.PI / 2 + angleStep * index;
    const r = (value / 100) * maxR;
    return [center + r * Math.cos(angle), center + r * Math.sin(angle)];
  }

  let gridRings = "";
  [0.25, 0.5, 0.75, 1].forEach(ratio => {
    const pts = axes.map((_, i) => pointFor(i, 100 * ratio).join(",")).join(" ");
    gridRings += `<polygon points="${pts}" fill="none" stroke="#d8cfa8" stroke-width="1"/>`;
  });

  let axisLines = "";
  let labels = "";
  axes.forEach((axis, i) => {
    const [x, y] = pointFor(i, 100);
    axisLines += `<line x1="${center}" y1="${center}" x2="${x}" y2="${y}" stroke="#d8cfa8" stroke-width="1"/>`;
    const [lx, ly] = pointFor(i, 116);
    labels += `<text x="${lx}" y="${ly}" text-anchor="middle" dominant-baseline="middle"
      font-size="13" font-weight="bold" fill="${DISC_INFO[axis].color}">${axis}</text>`;
  });

  const dataPts = axes.map((axis, i) => pointFor(i, percentages[axis] || 0).join(",")).join(" ");

  el.innerHTML = `
    <svg viewBox="0 0 200 200" style="width:100%;max-width:340px;height:auto;display:block;margin:0 auto;">
      ${gridRings}
      ${axisLines}
      <polygon points="${dataPts}" fill="#c9a24b" fill-opacity="0.35" stroke="#0e3b2e" stroke-width="2"/>
      ${labels}
    </svg>
  `;
}

